COLORS += [f"\033[38;5;{i}m" for i in range(16, 116)]


def colorize(text: str, color: str) -> str:
    """Wrap text in an ANSI color sequence and reset code."""

    return f"{color}{text}{RESET}"


def beep() -> None:
    """Emit a terminal bell sound."""

    sys.stdout.write("\a")
    sys.stdout.flush()


def animate(frames: list[str] = kitty_frames, delay: float = 0.12) -> None:
    """Play a looping animation made of ASCII frames.

    Args:
        frames (list[str]): Frames to display in sequence.
        delay (float, optional): Delay between frames in seconds.
    """

    color_index = 0
    x = 0
    while x < 700:
        for frame in frames:
            color = COLORS[color_index % len(COLORS)]
            print(colorize(frame, color))
            beep()
            color_index += 1
            time.sleep(delay)
            x += 1


if __name__ == "__main__":
    animate()
